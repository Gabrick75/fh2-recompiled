"""Generates app/src/fh2_censo.cpp: counting wrappers around the entry points of the Xbox D3D library in
Forza Horizon 2 ("censo" means census), adapted from NFSMW-Recompiled_ff (tools/renderprobe/gen_census.py).

FH2's D3D library is not one contiguous block as in NFSMW: its high level (device, state, draws, tiling) sits
with the C runtime at the start of the code (0x823F0000-0x82488000) and its low level (ring, swap, interrupts)
at 0x82B6A000-0x82B82000. Every function in those ranges called from outside them gets a wrapper, plus the
functions writing PM4 draw packets. Functions the app already hooks are skipped (one definition only).

Each guest function sub_X is a weak alias of __imp__sub_X: defining sub_X in the app replaces it for every
caller, and __imp__sub_X stays the original. With --fh2_censo=true the log gets, every 150 frames (a frame is a
call of the VdSwap caller), each entry's calls per frame and the arguments of its last call, and how many calls
had a shader container (0x102A11xx: pixel 00, vertex 01) at r3, r4 or r5 (the D3D shader constructors), and how
many had a shader object the constructors returned at r4 or r5 (SetVertexShader, SetPixelShader and the like).

    python3 tools/renderprobe/callgraph.py && python3 tools/renderprobe/gen_census_fh2.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
RANGES = [(0x823F0000, 0x82488000), (0x82B6A000, 0x82B82000)]
# Functions writing PM4 DRAW_INDX headers (found by their lis/ori constants).
DRAWS = ["sub_82418988", "sub_8241DA58", "sub_82425D68", "sub_82426180", "sub_82B72F10"]
SWAP = "sub_82B72118"  # calls VdSwap
# CreatePixelShader / CreateVertexShader (r3 = container, return the object in r3).
CONSTRUCTORS = {"sub_82B70280": "pixel", "sub_82B70468": "vertex"}

g = json.load(open(os.path.join(HERE, "callgraph.json")))
hooked = set()
for folder, _, names in os.walk(os.path.join(ROOT, "app", "src")):
    for name in names:
        if name.endswith(".cpp") and name != "fh2_censo.cpp":
            text = open(os.path.join(folder, name), encoding="utf-8", errors="replace").read()
            hooked |= set(re.findall(r"REX_HOOK_RAW\((sub_[0-9A-F]{8})\)", text))


def inside(f):
    a = int(f[4:], 16)
    return any(lo <= a < hi for lo, hi in RANGES)


callers = {}
for f, v in g.items():
    for c in v["calls"]:
        callers.setdefault(c, set()).add(f)
entries = sorted({f for f in g if f.startswith("sub_") and inside(f) and
                  any(not inside(c) for c in callers.get(f, ()))} | set(DRAWS) | {SWAP})
entries = [f for f in entries if f not in hooked]

out = ["""// GENERATED by tools/renderprobe/gen_census_fh2.py - do not edit.
// Counting wrappers around the entry points of the Xbox D3D library in Forza Horizon 2 (census for the native
// renderer), adapted from NFSMW-Recompiled_ff.
#include <algorithm>
#include <atomic>
#include <cstdint>
#include <cstdio>
#include <mutex>
#include <string>
#include <unordered_map>
#include <vector>

#include <rex/cvar.h>
#include <rex/hook.h>
#include <rex/logging.h>
#include <rex/ppc/context.h>
#include <rex/ppc/func.h>

#include <sys/uio.h>
#include <unistd.h>

REXCVAR_DEFINE_BOOL(fh2_censo, false, "FH2",
                    "Debug: count calls into the game's D3D library and log them every 150 frames");

namespace {
struct CensoEntry {
  const char* name;
  std::atomic<uint64_t> calls{0};
  std::atomic<uint32_t> r3{0}, r4{0}, r5{0}, r6{0}, r7{0}, lr{0};
  // Calls with a shader container at r3/r4/r5 (bit 0/1/2 of where), and the last container's flags.
  std::atomic<uint64_t> containers{0};
  std::atomic<uint32_t> where{0}, flags{0};
  std::atomic<uint64_t> objects{0};  // calls with a shader object at r4 or r5
  std::atomic<uint32_t> object_where{0};
};

// The shader objects the constructors returned (bit 0: pixel, 1: vertex).
std::mutex g_objects_mutex;
std::unordered_map<uint32_t, uint32_t> g_objects;
void RememberObject(uint32_t object, uint32_t kind) {
  std::lock_guard<std::mutex> lock(g_objects_mutex);
  g_objects[object] |= kind;
}
uint32_t ObjectKind(uint32_t object) {
  std::lock_guard<std::mutex> lock(g_objects_mutex);
  auto it = g_objects.find(object);
  return it == g_objects.end() ? 0 : it->second;
}
"""]
out.append(f"constexpr int kEntries = {len(entries)};")
out.append("CensoEntry g_entries[kEntries] = {")
out += [f'    {{"{f}"}},' for f in entries]
out.append("};")
out.append("""
// Reads a big-endian guest word without faulting on unmapped memory (an argument is not always a pointer).
bool ReadGuest(uint8_t* base, uint32_t address, uint32_t& value) {
  if (address < 0x10000 || address >= 0xFFFF0000u) return false;
  uint32_t raw;
  iovec local{&raw, 4}, remote{base + address, 4};
  if (process_vm_readv(getpid(), &local, 1, &remote, 1, 0) != 4) return false;
  value = __builtin_bswap32(raw);
  return true;
}

inline void Count(int i, PPCContext& ctx, uint8_t* base) {
  CensoEntry& e = g_entries[i];
  const uint32_t args[3] = {ctx.r3.u32, ctx.r4.u32, ctx.r5.u32};
  for (uint32_t k = 0; k < 3; ++k) {
    uint32_t w;
    if (ReadGuest(base, args[k], w) && (w & 0xFFFFFF00u) == 0x102A1100u) {
      e.containers.fetch_add(1, std::memory_order_relaxed);
      e.where.fetch_or(1u << k, std::memory_order_relaxed);
      e.flags.store(w, std::memory_order_relaxed);
    }
  }
  for (uint32_t k = 0; k < 2; ++k) {
    if (const uint32_t kind = ObjectKind(k ? ctx.r5.u32 : ctx.r4.u32)) {
      e.objects.fetch_add(1, std::memory_order_relaxed);
      e.object_where.fetch_or(kind << (k * 2), std::memory_order_relaxed);
    }
  }
  e.calls.fetch_add(1, std::memory_order_relaxed);
  e.r3.store(ctx.r3.u32, std::memory_order_relaxed);
  e.r4.store(ctx.r4.u32, std::memory_order_relaxed);
  e.r5.store(ctx.r5.u32, std::memory_order_relaxed);
  e.r6.store(ctx.r6.u32, std::memory_order_relaxed);
  e.r7.store(ctx.r7.u32, std::memory_order_relaxed);
  e.lr.store(static_cast<uint32_t>(ctx.lr), std::memory_order_relaxed);
}

void Report() {
  constexpr uint64_t kFrames = 150;
  static uint64_t frames = 0;
  if (++frames % kFrames) return;
  struct Row { int i; uint64_t n; };
  std::vector<Row> rows;
  for (int i = 0; i < kEntries; ++i) {
    uint64_t n = g_entries[i].calls.exchange(0, std::memory_order_relaxed);
    if (n) rows.push_back({i, n});
  }
  std::sort(rows.begin(), rows.end(), [](const Row& a, const Row& b) { return a.n > b.n; });
  std::string s;
  for (const Row& r : rows) {
    const CensoEntry& e = g_entries[r.i];
    char buf[300];
    std::snprintf(buf, sizeof(buf), "\\n  %s %10.2f/quadro  r3=%08X r4=%08X r5=%08X r6=%08X r7=%08X lr=%08X%s",
                  e.name, double(r.n) / kFrames, e.r3.load(), e.r4.load(), e.r5.load(), e.r6.load(),
                  e.r7.load(), e.lr.load(), "");
    if (const uint64_t c = e.containers.load()) {
      char extra[120];
      std::snprintf(extra, sizeof(extra), "  CONTEINER %llu vezes em r%s, ultimo %08X", (unsigned long long)c,
                    (e.where.load() & 1) ? "3" : (e.where.load() & 2) ? "4" : "5", e.flags.load());
      s += buf;
      s += extra;
      continue;
    }
    s += buf;
  }
  REXLOG_INFO("[censo] {} quadros, {} pontos de entrada usados:{}", kFrames, rows.size(), s);
  // Since the start: the functions that received shader containers (the constructors run while loading).
  std::string c;
  for (int i = 0; i < kEntries; ++i) {
    const CensoEntry& e = g_entries[i];
    if (const uint64_t n = e.objects.load()) {
      char buf[160];
      std::snprintf(buf, sizeof(buf), "\\n  %s %llu objetos de shader (r4 pixel/vertex = bits 0/1, r5 = 2/3: %u), lr=%08X",
                    e.name, (unsigned long long)n, e.object_where.load(), e.lr.load());
      c += buf;
    }
    if (const uint64_t n = e.containers.load()) {
      char buf[160];
      std::snprintf(buf, sizeof(buf), "\\n  %s %llu conteineres (r3/r4/r5 = bits %u), ultimo %08X, lr=%08X", e.name,
                    (unsigned long long)n, e.where.load(), e.flags.load(), e.lr.load());
      c += buf;
    }
  }
  if (!c.empty()) REXLOG_INFO("[censo] conteineres de shader recebidos desde o inicio:{}", c);
}
}  // namespace
""")
for i, f in enumerate(entries):
    out.append(f"REX_EXTERN(__imp__{f});")
    out.append(f"REX_HOOK_RAW({f}) {{")
    out.append(f"  if (REXCVAR_GET(fh2_censo)) {{")
    out.append(f"    Count({i}, ctx, base);")
    if f == SWAP:
        out.append("    Report();")
    out.append("  }")
    out.append(f"  __imp__{f}(ctx, base);")
    if f in CONSTRUCTORS:
        out.append(f"  RememberObject(ctx.r3.u32, {1 if CONSTRUCTORS[f] == 'pixel' else 2});")
    out.append("}")
path = os.path.join(ROOT, "app", "src", "fh2_censo.cpp")
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(f"{len(entries)} wrappers ({len(hooked)} hooked functions skipped), frame boundary {SWAP} -> {path}")
